import { apiClient } from './client';

/**
 * Analytics API
 * Handles platform-wide analytics and insights
 */

export interface PlatformStats {
  totalUsers: number;
  vendors: number;
  riders: number;
  totalOrders: number;
  completionRate: number;
  /** Platform commission from released escrows. null when staff lacks view_revenue. */
  totalRevenue: number | null;
  activeDisputes: number;
}

export interface AnalyticsSummary {
  totalOrders: number;
  /** Platform commission (null without view_revenue) */
  totalRevenue: number | null;
  totalUsers: number;
  /** Platform commission per order (null without view_revenue) */
  averageOrderValue: number | null;
  topCategories: Array<{
    category: string;
    orderCount: number;
    /** Sales volume (GMV). null without view_revenue */
    revenue: number | null;
  }>;
  topVendors: Array<{
    vendorId: string;
    vendorName: string;
    orderCount: number;
    /** Platform commission generated by this vendor's orders (null without view_revenue) */
    revenue: number | null;
  }>;
}

export interface TimeSeriesData {
  date: string;
  orders: number;
  revenue: number;
  users: number;
  [key: string]: string | number;
}

export interface AuctionAnalyticsSummary {
  totalAuctions: number;
  soldAuctions: number;
  sellThroughRate: number;
  /** Platform commission on auctions (null without view_revenue) */
  totalAuctionRevenue: number | null;
  averageBidsPerAuction: number;
  averageUniqueBiddersPerAuction: number;
  topCategories: Array<{
    categoryId: string;
    categoryName: string;
    totalRevenue: number;
    totalBids: number;
  }>;
  topAuctions: Array<{
    auctionId: string;
    title: string;
    categoryName: string;
    revenue: number;
    totalBids: number;
    uniqueBidders: number;
    status: string;
  }>;
}

export interface ConversionMetrics {
  averageTimeToFirstPurchaseHours: number;
  medianTimeToFirstPurchaseHours: number;
  conversionRate: number;
  totalUsers: number;
  purchasers: number;
  nonPurchasers: number;
  timeBuckets: {
    within24Hours: number;
    within7Days: number;
    within30Days: number;
    over30Days: number;
  };
  timeBucketsPercentage: {
    within24Hours: number;
    within7Days: number;
    within30Days: number;
    over30Days: number;
  };
}

export interface LiveStreamAnalyticsEntry {
  streamId: string;
  vendorId: string;
  vendorName: string;
  vendorAvatar?: string;
  title: string;
  currentViewers: number;
  totalViewers: number;
  totalSales: number;
  totalGifts: number;
  totalGiftValue: number;
  startedAt?: string;
}

export interface LiveSalesGamificationConfig {
  watchRewardsEnabled: boolean;
  watchTimeMinutes: number;
  fretiPerReward: number;
  dailyCapPerUser: number;
  perStreamCapPerUser: number;
  leaderboardEnabled: boolean;
  specialEventEnabled: boolean;
  specialEventName?: string;
  defaultOrderWeight: number;
  defaultViewerWeight: number;
  defaultRevenueWeight: number;
}

export interface LiveSalesAnalytics {
  currentlyLiveStreams: number;
  currentlyLiveVendors: number;
  totalActiveViewers: number;
  streams: LiveStreamAnalyticsEntry[];
  gamification: LiveSalesGamificationConfig | null;
}

export interface VendorByOrders {
  vendorId: string;
  vendorName: string;
  completedOrders: number;
  /** Total order value (GMV). null without view_revenue */
  totalRevenue: number | null;
  averageOrderValue: number | null;
}

export interface ProductsTabAnalytics {
  /** Total tab visits within the date range */
  totalVisits: number;
  /** Unique users who visited within the date range */
  uniqueVisitors: number;
  /** Unique users who have ever visited (all-time) */
  allTimeUniqueVisitors: number;
  /** totalVisits / uniqueVisitors within range */
  visitsPerVisitor: number;
  /** Users whose first-ever visit falls within the date range */
  firstTimeVisitorsInRange: number;
  /** Users with more than one visit (all-time) */
  repeatVisitors: number;
  /** % of all-time visitors who came back (0-100) */
  repeatVisitRate: number;
  /** % of all registered users who have ever visited (0-100) */
  adoptionRate: number;
  discoveryLatency: {
    /** Users bucketed by signup -> first-visit time */
    buckets: { within24h: number; within7d: number; within30d: number; over30d: number };
    medianHours: number;
    meanHours: number;
    sampleSize: number;
  };
  dateRange: { start: string; end: string };
}

export interface PlatformListingsAnalytics {
  products: {
    total: number;
    draft: number;
    multiItemListings: number;
    /** Sum of price * quantity for active listings (GMV). null without view_revenue */
    listedValue: number | null;
  };
  services: {
    total: number;
    draft: number;
    /** Sum of base_price for active services (GMV). null without view_revenue */
    listedValue: number | null;
  };
  auctions: {
    /** scheduled + active (still open to bidding) */
    open: number;
    scheduled: number;
    active: number;
    ended: number;
    /** Sum of current bid (or starting price) for open auctions. null without view_revenue */
    listedValue: number | null;
  };
  /** Combined listed value across products, services, and auctions. null without view_revenue */
  totalListedGMV: number | null;
}

export interface VendorsRidersAnalytics {
  vendors: {
    total: number;
    active: number;
    suspended: number;
    /** Vendors with the user_profiles.is_verified badge */
    verified: number;
  };
  riders: {
    /** Everyone flagged as a rider on user_profiles (registered, not necessarily verified) */
    totalRegistered: number;
    /** Verification applications by status (rider_verifications) */
    applications: {
      inProgress: number;
      underReview: number;
      verified: number;
      rejected: number;
    };
    /** Riders who passed verification, by ongoing status (verified_riders) */
    verified: {
      active: number;
      suspended: number;
      terminated: number;
      total: number;
    };
  };
}

export const analyticsAPI = {
  /**
   * Get platform statistics
   * GET /admin/analytics/stats
   */
  getPlatformStats: async (): Promise<PlatformStats> => {
    return apiClient.get<PlatformStats>('/admin/analytics/stats');
  },

  /**
   * Get analytics summary
   * GET /admin/analytics/summary
   */
  getAnalyticsSummary: async (): Promise<AnalyticsSummary> => {
    return apiClient.get<AnalyticsSummary>('/admin/analytics/summary');
  },

  /**
   * Get time series data
   * GET /admin/analytics/timeseries?start=2024-01-01&end=2024-01-31&period=daily
   */
  getTimeSeries: async (
    start: string,
    end: string,
    period: 'daily' | 'weekly' | 'monthly' = 'daily',
    timezoneOffset?: number,
  ): Promise<TimeSeriesData[]> => {
    const params = new URLSearchParams();
    params.append('start', start);
    params.append('end', end);
    params.append('period', period);
    if (timezoneOffset !== undefined) {
      params.append('timezoneOffset', timezoneOffset.toString());
    }

    return apiClient.get<TimeSeriesData[]>(`/admin/analytics/timeseries${params.toString() ? `?${params.toString()}` : ''}`);
  },

  /**
   * Get auction analytics summary
   * GET /admin/analytics/auctions/summary
   */
  getAuctionAnalyticsSummary: async (start?: string, end?: string): Promise<AuctionAnalyticsSummary> => {
    const params = new URLSearchParams();
    if (start) params.append('start', start);
    if (end) params.append('end', end);

    const query = params.toString() ? `?${params.toString()}` : '';
    return apiClient.get<AuctionAnalyticsSummary>(`/admin/analytics/auctions/summary${query}`);
  },

  /**
   * Get conversion metrics (time to first purchase)
   * GET /admin/analytics/conversion-metrics
   */
  getConversionMetrics: async (): Promise<ConversionMetrics> => {
    return apiClient.get<ConversionMetrics>('/admin/analytics/conversion-metrics');
  },

  /**
   * Get top vendors by completed orders (order-count-based ranking)
   * GET /admin/analytics/vendors-by-orders
   */
  getTopVendorsByOrders: async (): Promise<VendorByOrders[]> => {
    return apiClient.get<VendorByOrders[]>('/admin/analytics/vendors-by-orders');
  },

  /**
   * Get live sales / gamification analytics
   * GET /admin/analytics/live-sales
   */
  getLiveSalesAnalytics: async (): Promise<LiveSalesAnalytics> => {
    return apiClient.get<LiveSalesAnalytics>('/admin/analytics/live-sales');
  },

  /**
   * Get products tab discovery analytics (HomeScreen tab visits)
   * GET /admin/analytics/products-tab?start=...&end=...
   */
  getProductsTabAnalytics: async (start?: string, end?: string): Promise<ProductsTabAnalytics> => {
    const params = new URLSearchParams();
    if (start) params.append('start', start);
    if (end) params.append('end', end);

    const query = params.toString() ? `?${params.toString()}` : '';
    return apiClient.get<ProductsTabAnalytics>(`/admin/analytics/products-tab${query}`);
  },

  /**
   * Get platform listings inventory + listed GMV (products/services/auctions)
   * GET /admin/analytics/listings
   */
  getPlatformListings: async (): Promise<PlatformListingsAnalytics> => {
    return apiClient.get<PlatformListingsAnalytics>('/admin/analytics/listings');
  },

  /**
   * Get vendor + rider registration counts and status breakdown
   * GET /admin/analytics/vendors-riders
   */
  getVendorsRiders: async (): Promise<VendorsRidersAnalytics> => {
    return apiClient.get<VendorsRidersAnalytics>('/admin/analytics/vendors-riders');
  },
};
